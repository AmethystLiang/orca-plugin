import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const read = path => JSON.parse(fs.readFileSync(require.resolve(path), 'utf8'));
const source = read('emojibase-data/en/data.json');
const shortcodes = read('emojibase-data/en/shortcodes/github.json');
const emoji = source.filter(e => Number.isInteger(e.group) && e.group !== 2)
  .sort((a, b) => a.order - b.order).map(e => {
    const aliases = [shortcodes[e.hexcode] ?? []].flat();
    const skins = Object.fromEntries((e.skins ?? []).filter(s => typeof s.tone === 'number').map(s => [s.tone, s.emoji]));
    return [e.emoji, e.label, e.group, aliases, e.tags ?? [], skins, e.version];
  });
fs.writeFileSync(new URL('panel/emoji-data.js', root), `// Generated by npm run build:data; Emojibase 18.0.0 (MIT).\nexport default ${JSON.stringify(emoji)};\n`);
fs.copyFileSync(require.resolve('emojibase-data/LICENSE'), new URL('assets/EMOJIBASE-LICENSE', root));
console.log(`Bundled ${emoji.length} emoji, with search tags, GitHub shortcodes, and skin tones.`);
